"""Shared monitor discovery, live application, and persistence for hk-display."""

from __future__ import annotations

import json
import math
import os
import re
import subprocess
import tempfile
from pathlib import Path
from typing import Any

STATE_HOME = (
    Path(os.environ.get("XDG_STATE_HOME", Path.home() / ".local/state"))
    / "hyprkarl"
    / "display"
)
STATE_PATH = STATE_HOME / "layout.json"
LUA_PATH = STATE_HOME / "monitors.lua"
INTERNAL_OUTPUT = re.compile(r"^(eDP|LVDS|DSI)-")
SCALE_PRESETS = (1.0, 1.25, 1.5, 1.6, 2.0, 3.0, 4.0)


def run(command: list[str]) -> str:
    return subprocess.run(
        command,
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def monitors() -> list[dict[str, Any]]:
    return json.loads(run(["hyprctl", "monitors", "all", "-j"]))


def load_layout() -> dict[str, Any]:
    if not STATE_PATH.exists():
        return {"version": 1, "outputs": {}}
    with STATE_PATH.open(encoding="utf-8") as source:
        return json.load(source)


def mode_string(monitor: dict[str, Any]) -> str:
    refresh = f"{float(monitor['refreshRate']):.3f}".rstrip("0").rstrip(".")
    return f"{monitor['width']}x{monitor['height']}@{refresh}"


def active_config(monitor: dict[str, Any]) -> dict[str, Any]:
    return {
        "enabled": True,
        "mode": mode_string(monitor),
        "position": f"{monitor['x']}x{monitor['y']}",
        "scale": float(monitor["scale"]),
        "transform": int(monitor["transform"]),
    }


def capture_layout(
    current: list[dict[str, Any]],
    previous: dict[str, Any],
) -> dict[str, Any]:
    outputs = dict(previous.get("outputs", {}))
    for monitor in current:
        name = monitor["name"]
        if monitor.get("disabled", False):
            config = dict(outputs.get(name, {}))
            config["enabled"] = False
            outputs[name] = config
        else:
            outputs[name] = active_config(monitor)
    return {"version": 1, "outputs": outputs}


def lua_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, float):
        return f"{value:.6f}".rstrip("0").rstrip(".")
    return str(value)


def monitor_lua(name: str, config: dict[str, Any]) -> str:
    if not config.get("enabled", False):
        return "hl.monitor({ output = " + lua_value(name) + ", disabled = true })"

    fields = [
        ("output", name),
        ("disabled", False),
        ("mode", config.get("mode", "preferred")),
        ("position", config.get("position", "auto")),
        ("scale", config.get("scale", "auto")),
        ("transform", config.get("transform", 0)),
    ]
    values = ", ".join(f"{key} = {lua_value(value)}" for key, value in fields)
    return f"hl.monitor({{ {values} }})"


def render_lua(layout: dict[str, Any]) -> str:
    lines = [
        "-- Generated by hk-display. Personal hyprkarl/hypr/monitors.lua rules load afterward.",
    ]
    for name in sorted(layout["outputs"]):
        lines.append(monitor_lua(name, layout["outputs"][name]))
    return "\n".join(lines) + "\n"


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        delete=False,
    ) as temporary:
        temporary.write(content)
        temporary.flush()
        os.fsync(temporary.fileno())
        temporary_path = Path(temporary.name)
    os.replace(temporary_path, path)


def save_layout(layout: dict[str, Any]) -> None:
    atomic_write(
        STATE_PATH,
        json.dumps(layout, ensure_ascii=False, separators=(",", ":")) + "\n",
    )
    atomic_write(LUA_PATH, render_lua(layout))


def apply_monitor(name: str, config: dict[str, Any]) -> None:
    result = run(["hyprctl", "eval", monitor_lua(name, config)]).strip()
    if result != "ok":
        raise RuntimeError(result)


def apply_layout_change(
    previous: dict[str, Any],
    layout: dict[str, Any],
    name: str,
    config: dict[str, Any],
) -> None:
    # A disabled output can destroy the panel process that invoked this command.
    # Persist first so every layout action survives that lifecycle boundary.
    save_layout(layout)
    try:
        apply_monitor(name, config)
    except Exception:
        save_layout(previous)
        raise


def find_monitor(current: list[dict[str, Any]], name: str) -> dict[str, Any]:
    for monitor in current:
        if monitor["name"] == name:
            return monitor
    raise RuntimeError(f"Display not found: {name}")


def resolve_target(
    current: list[dict[str, Any]],
    requested: str,
) -> dict[str, Any]:
    if requested:
        return find_monitor(current, requested)
    for monitor in current:
        if monitor.get("focused", False):
            return monitor
    for monitor in current:
        if not monitor.get("disabled", False):
            return monitor
    raise RuntimeError("No active display found")


def clean_scale(requested: float, width: int, height: int) -> float:
    divisor = math.gcd(round(width * 120), round(height * 120))
    units = min(round(requested * 120), divisor)
    while divisor % units != 0:
        units += 1
    return units / 120


def scale_presets(monitor: dict[str, Any]) -> list[float]:
    if monitor.get("disabled", False):
        return list(SCALE_PRESETS)
    values: list[float] = []
    for preset in SCALE_PRESETS:
        effective = clean_scale(preset, monitor["width"], monitor["height"])
        if effective not in values:
            values.append(effective)
    return values


def backlight_device(output: str) -> str | None:
    if not INTERNAL_OUTPUT.match(output):
        return None
    candidates = sorted(Path("/sys/class/backlight").glob("amdgpu_bl*"))
    candidates += [Path("/sys/class/backlight/intel_backlight")]
    candidates += sorted(Path("/sys/class/backlight").glob("acpi_video*"))
    candidates += sorted(Path("/sys/class/backlight").glob("*"))
    for candidate in candidates:
        if candidate.is_dir():
            return candidate.name
    return None


def brightness(output: str) -> dict[str, Any]:
    device = backlight_device(output)
    if device is None:
        return {"available": False, "percent": 0}
    fields = run(["brightnessctl", "-d", device, "-m"]).strip().split(",")
    return {
        "available": True,
        "percent": int(fields[3].removesuffix("%")),
    }


def set_brightness(output: str, percent: int) -> int:
    device = backlight_device(output)
    if device is None:
        raise RuntimeError(f"Brightness control is unavailable for {output}")
    run(["brightnessctl", "-q", "-d", device, "set", f"{percent}%"])
    return percent


def display_state(requested: str) -> dict[str, Any]:
    current = monitors()
    target = resolve_target(current, requested)
    previous = load_layout()
    saved_outputs = previous.get("outputs", {})
    outputs = []

    for monitor in current:
        enabled = not monitor.get("disabled", False)
        saved = saved_outputs.get(monitor["name"], {})
        outputs.append(
            {
                "name": monitor["name"],
                "description": monitor.get("description", ""),
                "enabled": enabled,
                "focused": monitor.get("focused", False),
                "width": monitor.get("width", 0) or 0,
                "height": monitor.get("height", 0) or 0,
                "refreshRate": monitor.get("refreshRate", 0) or 0,
                "scale": monitor.get("scale", saved.get("scale", 1)),
            }
        )

    return {
        "target": target["name"],
        "outputs": outputs,
        "scale": target.get(
            "scale", saved_outputs.get(target["name"], {}).get("scale", 1)
        ),
        "scalePresets": scale_presets(target),
        "brightness": brightness(target["name"]),
    }


def set_scale(name: str, requested: float) -> float:
    if requested < 1 or requested > 4:
        raise RuntimeError("Scale must be between 1 and 4")
    current = monitors()
    monitor = find_monitor(current, name)
    if monitor.get("disabled", False):
        raise RuntimeError(f"Display is disabled: {name}")

    effective = clean_scale(requested, monitor["width"], monitor["height"])
    previous = load_layout()
    layout = capture_layout(current, previous)
    config = active_config(monitor)
    config["scale"] = effective
    layout["outputs"][name] = config
    apply_layout_change(previous, layout, name, config)
    return effective


def toggle(name: str) -> bool:
    current = monitors()
    monitor = find_monitor(current, name)
    enabled = not monitor.get("disabled", False)
    if enabled:
        active_count = sum(not item.get("disabled", False) for item in current)
        if active_count == 1:
            raise RuntimeError("The last active display cannot be disabled")

    previous = load_layout()
    layout = capture_layout(current, previous)
    if enabled:
        config = dict(layout["outputs"][name])
        config["enabled"] = False
    else:
        config = dict(previous.get("outputs", {}).get(name, {}))
        config.update(
            {
                "enabled": True,
                "mode": config.get("mode", "preferred"),
                "position": config.get("position", "auto"),
                "scale": config.get("scale", "auto"),
                "transform": config.get("transform", 0),
            }
        )

    layout["outputs"][name] = config

    apply_layout_change(previous, layout, name, config)
    return config["enabled"]
